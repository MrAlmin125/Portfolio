<?php
/**
 * api/ip_block.php
 *
 * IP blocking for the whole site — not just the admin panel. index.html
 * (and every other file) is a static file Apache serves directly, so PHP
 * can't intercept a request to it. The only place that CAN stop it is
 * Apache itself, via .htaccess — so every time an IP is blocked or
 * unblocked here, the site's root .htaccess is rewritten with a fresh
 * rule that redirects that IP to blocked.html (see that file) before
 * Apache serves anything else to it.
 *
 * admin.php, login.php, and the two admin API endpoints are always
 * exempted, so an admin can never accidentally lock themselves out of
 * the panel.
 */

const IP_BLOCK_HTACCESS_PATH = __DIR__ . '/../.htaccess';
const IP_BLOCK_MARKER_START  = '# BEGIN amin-portfolio IP block (auto-generated by admin.php — do not edit by hand)';
const IP_BLOCK_MARKER_END    = '# END amin-portfolio IP block';

function ip_block_list(PDO $pdo): array {
  $stmt = $pdo->query('SELECT ip_address, reason, blocked_at FROM blocked_ips ORDER BY blocked_at DESC');
  return $stmt->fetchAll();
}

function ip_block_add(PDO $pdo, string $ip, ?string $reason): bool {
  $stmt = $pdo->prepare(
    'INSERT INTO blocked_ips (ip_address, reason)
     VALUES (:ip, :reason)
     ON DUPLICATE KEY UPDATE reason = VALUES(reason)'
  );
  $stmt->execute(['ip' => $ip, 'reason' => ($reason !== '' ? $reason : null)]);
  return ip_block_regenerate_htaccess($pdo);
}

function ip_block_remove(PDO $pdo, string $ip): bool {
  $stmt = $pdo->prepare('DELETE FROM blocked_ips WHERE ip_address = :ip');
  $stmt->execute(['ip' => $ip]);
  return ip_block_regenerate_htaccess($pdo);
}

/**
 * The mod_rewrite rule this generates. Exposed separately so the admin
 * panel can display it for manual copy-paste if the site's .htaccess
 * turns out not to be writable by PHP (common on some shared hosts).
 */
function ip_block_rule_text(array $ips): string {
  if (empty($ips)) return '';

  $lines = [IP_BLOCK_MARKER_START];
  $lines[] = 'RewriteEngine On';
  $lines[] = 'RewriteCond %{REQUEST_URI} !^/admin\.php$ [NC]';
  $lines[] = 'RewriteCond %{REQUEST_URI} !^/login\.php$ [NC]';
  $lines[] = 'RewriteCond %{REQUEST_URI} !^/api/admin_action\.php$ [NC]';
  $lines[] = 'RewriteCond %{REQUEST_URI} !^/api/user_manager\.php$ [NC]';
  // Exempted so a blocked visitor can actually see the page explaining
  // that — without this, the rule below would redirect blocked.html to
  // itself in an infinite loop.
  $lines[] = 'RewriteCond %{REQUEST_URI} !^/blocked\.html$ [NC]';

  $count = count($ips);
  foreach ($ips as $i => $ip) {
    $escaped = preg_quote($ip, '/');
    $isLast = ($i === $count - 1);
    $lines[] = 'RewriteCond %{REMOTE_ADDR} ^' . $escaped . '$' . ($isLast ? '' : ' [OR]');
  }
  // A blocked visitor is redirected to a clear, on-brand explanation
  // page rather than shown a raw server error — R=302 (not permanent),
  // since being unblocked later should immediately restore normal access.
  $lines[] = 'RewriteRule ^ /blocked.html [R=302,L]';
  $lines[] = IP_BLOCK_MARKER_END;

  return implode("\n", $lines) . "\n";
}

/**
 * Rewrites the root .htaccess's auto-generated block (between the START/
 * END markers) to match the current blocked_ips table, leaving any other
 * content in the file untouched. Returns true on success; false if the
 * file couldn't be written (e.g. the host doesn't allow PHP to modify
 * .htaccess) — the admin panel falls back to showing the rule text for
 * the site owner to paste in manually.
 */
function ip_block_regenerate_htaccess(PDO $pdo): bool {
  $ips = array_column(ip_block_list($pdo), 'ip_address');
  $newBlock = ip_block_rule_text($ips);

  $existing = is_file(IP_BLOCK_HTACCESS_PATH) ? file_get_contents(IP_BLOCK_HTACCESS_PATH) : '';
  if ($existing === false) $existing = '';

  $pattern = '/' . preg_quote(IP_BLOCK_MARKER_START, '/') . '.*?' . preg_quote(IP_BLOCK_MARKER_END, '/') . '\n?/s';

  if (preg_match($pattern, $existing)) {
    $updated = preg_replace($pattern, $newBlock, $existing);
  } else {
    $updated = rtrim($existing) . ($existing !== '' ? "\n\n" : '') . $newBlock;
  }

  return @file_put_contents(IP_BLOCK_HTACCESS_PATH, $updated) !== false;
}
